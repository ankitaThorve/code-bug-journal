// while loop -------------------------------
let i = 0;
while (i < 3) {
  console.log(i);
  i++;
}

// do...while loop ---------------------------
/**
 * syntax :
 * do{
 *  // loop body
 * } while (condition)
 */

let j = 0;
do {
  console.log(j);
  j++;
} while (j < 3);

// The loop will first execute the body, then check the condition, and, while it's truthy, execute it again and again.

